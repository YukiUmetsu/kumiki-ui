/** Shared rules for the real-source footage checks (K1): a barcode that carries each source frame's index,
 * the rotation mapping, and the expected output-to-source mapping. Used by the fixture generator and the
 * Chrome verifier, so both sides agree on what a correct frame looks like. No browser, no I/O.
 */

export const BARCODE_BITS = 24;

/** Pixel layout of the barcode band for a frame of the given size. */
export function barcodeLayout(width, height) {
  const cellW = Math.floor(width * 0.9 / BARCODE_BITS);
  return {
    cellW,
    x0: Math.round((width - cellW * BARCODE_BITS) / 2),
    y0: Math.round(height * 0.14),
    bandH: Math.max(8, Math.round(height * 0.12)),
  };
}

/** Paint a source frame index into an RGB24 buffer: black/white cells, bit 0 leftmost. */
export function paintIndex(buffer, width, height, index) {
  buffer.fill(60);
  const { cellW, x0, y0, bandH } = barcodeLayout(width, height);
  for (let bit = 0; bit < BARCODE_BITS; bit += 1) {
    const value = (index >> bit) & 1 ? 255 : 0;
    for (let y = y0; y < y0 + bandH; y += 1) {
      for (let x = x0 + bit * cellW; x < x0 + (bit + 1) * cellW; x += 1) {
        const offset = (y * width + x) * 3;
        buffer[offset] = buffer[offset + 1] = buffer[offset + 2] = value;
      }
    }
  }
  return buffer;
}

/** Read the index back from an RGBA canvas buffer of the given display size. Returns NaN if a cell is ambiguous. */
export function readIndex(rgba, width, height) {
  const { cellW, x0, y0, bandH } = barcodeLayout(width, height);
  let index = 0;
  for (let bit = 0; bit < BARCODE_BITS; bit += 1) {
    const x = x0 + bit * cellW + Math.floor(cellW / 2), y = y0 + Math.floor(bandH / 2);
    const offset = (y * width + x) * 4;
    const luminance = (rgba[offset] + rgba[offset + 1] + rgba[offset + 2]) / 3;
    if (luminance > 200) index |= 1 << bit;
    else if (luminance >= 55 && luminance <= 200) return Number.NaN;
  }
  return index;
}

/**
 * A portrait frame (displayWidth × displayHeight) stored as the landscape coded frame that a 90° counter-clockwise
 * display rotation (ffmpeg's -display_rotation 90) turns back upright. The coded frame is the display rotated
 * clockwise: coded(i, j) = display(row displayHeight − 1 − j, column i).
 */
export function codedForPortrait(displayBuffer, displayWidth, displayHeight) {
  const codedWidth = displayHeight, codedHeight = displayWidth;
  const coded = Buffer.alloc(codedWidth * codedHeight * 3);
  for (let i = 0; i < codedHeight; i += 1) {
    for (let j = 0; j < codedWidth; j += 1) {
      const from = ((displayHeight - 1 - j) * displayWidth + i) * 3, to = (i * codedWidth + j) * 3;
      coded[to] = displayBuffer[from]; coded[to + 1] = displayBuffer[from + 1]; coded[to + 2] = displayBuffer[from + 2];
    }
  }
  return { buffer: coded, width: codedWidth, height: codedHeight };
}

/**
 * The counter-clockwise twin for a 270° display rotation (ffmpeg -display_rotation 270, i.e. 90° clockwise):
 * coded = display rotated counter-clockwise, so the display rotation turns it back upright.
 * coded(i, j) = display(row j, column displayWidth − 1 − i).
 */
export function codedForPortraitCcw(displayBuffer, displayWidth, displayHeight) {
  const codedWidth = displayHeight, codedHeight = displayWidth;
  const coded = Buffer.alloc(codedWidth * codedHeight * 3);
  for (let i = 0; i < codedHeight; i += 1) {
    for (let j = 0; j < codedWidth; j += 1) {
      const from = (j * displayWidth + (displayWidth - 1 - i)) * 3, to = (i * codedWidth + j) * 3;
      coded[to] = displayBuffer[from]; coded[to + 1] = displayBuffer[from + 1]; coded[to + 2] = displayBuffer[from + 2];
    }
  }
  return { buffer: coded, width: codedWidth, height: codedHeight };
}

/** Kept source frames after a select filter, with the index of each kept frame (ground truth). */
export function keptIndices(totalFrames, drop) {
  const kept = [];
  for (let n = 0; n < totalFrames; n += 1) if (!drop(n)) kept.push(n);
  return kept;
}

/**
 * Expected source frame for an output frame at an authored output rate, mirroring the documented floor policy:
 * the last source frame whose presentation time is at or before the output time. Written independently of the
 * registry so a mismatch means the browser path disagrees with the policy, not that the same code agrees with itself.
 */
export function expectedSourceFrame(timestamps, outputFrame, outputFps) {
  const time = outputFrame * outputFps.den / outputFps.num;
  let best = 0;
  for (let i = 0; i < timestamps.length; i += 1) {
    if (timestamps[i] <= time + 1e-6) best = i;
    else break;
  }
  return best;
}

