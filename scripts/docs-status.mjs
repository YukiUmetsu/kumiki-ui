#!/usr/bin/env node
/** Generate docs/component-status.md from the catalog and the docs folders, so status has one source.
 * Every component spec and verification report is linked here, so docs/INDEX.md can stay short.
 * npm run docs:status [-- --check]   --check fails if the committed file is stale.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { prepareCatalog } from "./catalog-data.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = path.join(ROOT, "docs"), TARGET = path.join(DOCS, "component-status.md");
const heading = file => /^#\s+(.+)$/m.exec(readFileSync(file, "utf8"))?.[1]?.trim() ?? path.basename(file, ".md");
const markdown = folder => readdirSync(path.join(DOCS, folder)).filter(name => name.endsWith(".md")).sort();
const cell = text => text.replace(/\|/g, "\\|");
const REVIEW = { approved: "approved", "not-reviewed": "**not reviewed**", "not-applicable": "—" };

const packs = prepareCatalog().filter(entry => entry.type === "pack").sort((a, b) => a.name.localeCompare(b.name, "en"));
const specOf = entry => entry.docs?.replace(/^docs\//, "");
const linked = new Set(packs.map(specOf));
const others = markdown("component-specs").filter(name => !linked.has("component-specs/" + name));
const reports = markdown("verification");
const counts = packs.reduce((all, entry) => ({ ...all, [entry.review]: (all[entry.review] ?? 0) + 1 }), {});

const text = [
  "# Component status",
  "",
  "Generated by `npm run docs:status` from the catalog. Do not edit. `npm run catalog:check` fails if this file is stale.",
  "",
  `${packs.length} registered packs. Review: ${counts.approved ?? 0} approved, ${counts["not-reviewed"] ?? 0} not reviewed, ${counts["not-applicable"] ?? 0} with no visual approval gate.`,
  "A pack in this table is installable. That does not mean that it is visually approved. Read its spec and its verification report.",
  "",
  "## Registered packs",
  "",
  "| Pack | Group | Renderer | Spec | Story | Review |",
  "|---|---|---|---|---|---|",
  ...packs.map(entry => `| \`${entry.name}\` | ${entry.domain} | ${entry.renderer} | ${specOf(entry) ? `[spec](${specOf(entry)})` : "—"} | ${entry.storyId ? `\`${entry.storyId}\`` : "—"} | ${REVIEW[entry.review]} |`),
  "",
  "## Specs with no pack of their own",
  "",
  ...others.map(name => `- [${cell(heading(path.join(DOCS, "component-specs", name)))}](component-specs/${name})`),
  "",
  "## Verification reports",
  "",
  ...reports.map(name => `- [${cell(heading(path.join(DOCS, "verification", name)))}](verification/${name})`),
  "",
].join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(TARGET, "utf8") !== text) throw Error("docs/component-status.md is stale. Run npm run docs:status.");
} else {
  writeFileSync(TARGET, text);
  console.log("Wrote docs/component-status.md (" + packs.length + " packs, " + others.length + " other specs, " + reports.length + " reports).");
}
