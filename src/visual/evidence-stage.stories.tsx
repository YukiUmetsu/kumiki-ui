const OUTPUTS = [{ id: "portrait", width: 1080, height: 1920, max: 300 }, { id: "landscape", width: 1920, height: 1080, max: 560 }];
const note: CSSProperties = { margin: 0, font: "400 13px/1.5 var(--km-font-body, system-ui, sans-serif)", color: "var(--km-text-muted, #5b6472)" };
const tone = (d: EvidenceDiagnostic) => d.severity === "error" ? "var(--km-text-danger, #b91c1c)" : "var(--km-status-warning, #b45309)";

function Investigation({ startFrame }: { startFrame: number }) {
  const total = evidenceDuration(SPEC);
  const [frame, setFrame] = useState(startFrame);
  const [playing, setPlaying] = useState(false);
  const [diagnostics, setDiagnostics] = useState<Record<string, EvidenceDiagnostic[]>>({});
  useEffect(() => {
    if (!playing) return;
    let raf = 0, origin: number | undefined; const from = frame >= total - 1 ? 0 : frame;
    const tick = (t: number) => { origin ??= t; const next = from + Math.floor((t - origin) * 30 / 1000);
      if (next >= total) { setFrame(total - 1); setPlaying(false); return; } setFrame(next); raf = requestAnimationFrame(tick); };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [playing]); // eslint-disable-line react-hooks/exhaustive-deps -- restart only on play/pause
  // Framing diagnostics name their output; shared ones appear once.
  const all = [...new Map(Object.values(diagnostics).flat().map(d => [`${d.code}|${d.message}`, d])).values()];
  return <section style={{ padding: 20, display: "grid", gap: 16, background: "var(--km-surface-canvas, #f6f7f9)", color: "var(--km-text-primary, #1f2937)", font: "400 14px/1.5 var(--km-font-body, system-ui, sans-serif)" }}>
    <div style={{ display: "flex", gap: 12, alignItems: "center", flexWrap: "wrap" }}>
      <button type="button" onClick={() => setPlaying(p => !p)} style={{ padding: "8px 16px", borderRadius: 8, font: "600 14px/1 var(--km-font-body, system-ui)" }}>{playing ? "Pause" : "Play"}</button>
      <input aria-label="Seek" type="range" min={0} max={total - 1} value={frame} onChange={e => { setPlaying(false); setFrame(Number(e.target.value)); }} style={{ flex: "1 1 260px" }} />
      <span style={{ fontFamily: "var(--km-font-mono, ui-monospace, monospace)" }}>frame {frame}</span>
    </div>
    <div style={{ display: "flex", gap: 24, flexWrap: "wrap", alignItems: "flex-start" }}>
      {OUTPUTS.map(o => <figure key={o.id} style={{ margin: 0, width: "100%", maxWidth: o.max, display: "grid", gap: 6 }}>
        <EvidenceStage spec={SPEC} frame={frame} width={o.width} height={o.height} style={{ borderRadius: 12 }}
          onDiagnostics={d => setDiagnostics(prev => ({ ...prev, [o.id]: d }))} />
        <figcaption style={note}>{o.width}×{o.height}</figcaption>
      </figure>)}
    </div>
    {all.length ? <ul style={{ margin: 0, paddingLeft: 20 }}>{all.map((d, i) => <li key={i}><strong style={{ color: tone(d) }}>{d.code}</strong> — {d.message}</li>)}</ul>
      : <p style={{ ...note, color: "var(--km-status-success, #15803d)", fontWeight: 600 }}>Provenance, rights, quotes, cell values, regions and framing all check out in both outputs.</p>}
    <p style={note}>Document and data are fictional samples; the photo is a still of the in-house synthetic conveyor footage. EvidenceStage checks that citations match their sources, not that the sources are true.</p>
  </section>;
}

/* Evidence the stage refuses, each with its reason. */
const BROKEN: EvidenceStageSpec = { ...SPEC, sources: [
    { ...SOURCES[0], anchors: [{ id: "misquote", quote: "loaded by stop order" }, { id: "hidden", quote: "555-0100" }, { id: "stop-order", quote: "loaded in stop order" }] } as EvidenceSource,
    { ...SOURCES[1], provenance: { ...SOURCES[1].provenance, rights: { status: "owned", reference: "" } }, anchors: [{ id: "label", rect: { x: 3700, y: 1192, width: 360, height: 176 } }] } as EvidenceSource,
    { ...SOURCES[2], anchors: [{ id: "r7-start", rowId: "r7", columnId: "start", expect: "10:40" }] } as EvidenceSource,
  ], conclusion: { text: "Arrives at 10:40 [1] [4].", citations: [{ marker: "[1]", sourceId: "policy", anchorId: "per-stop" }] } };
function Refusals() {
  const diagnostics = useMemo(() => { const measure = createCanvasMeasurer({}), layout = layoutEvidenceSources(BROKEN, measure);
    return [...layout.diagnostics, ...validateEvidenceStage(BROKEN, layout.surfaces, [{ width: 1080, height: 1920 }], { measure })]; }, []);
  return <section style={{ padding: 20, display: "grid", gap: 8, font: "400 14px/1.5 var(--km-font-body, system-ui, sans-serif)", color: "var(--km-text-primary, #1f2937)" }}>
    <ul style={{ margin: 0, paddingLeft: 20 }}>{diagnostics.map((d, i) => <li key={i}><strong style={{ color: tone(d) }}>{d.code}</strong> — {d.message}</li>)}</ul>
  </section>;
}

