const fmt=(v:number)=>v.toFixed(2);
function pointOnAxis(axis:Axis,t:number){
  const u=1-t;
  const [p0,p1,p2,p3]=axis;
  const x=u*u*u*p0[0]+3*u*u*t*p1[0]+3*u*t*t*p2[0]+t*t*t*p3[0];
  const y=u*u*u*p0[1]+3*u*u*t*p1[1]+3*u*t*t*p2[1]+t*t*t*p3[1];
  const dx=3*u*u*(p1[0]-p0[0])+6*u*t*(p2[0]-p1[0])+3*t*t*(p3[0]-p2[0]);
  const dy=3*u*u*(p1[1]-p0[1])+6*u*t*(p2[1]-p1[1])+3*t*t*(p3[1]-p2[1]);
  const length=Math.hypot(dx,dy);
  if(length<1e-6)throw new RangeError("Rose value plane has degenerate tangent");
  return {x,y,dx:dx/length,dy:dy/length};
}
function contact(x:number,y:number,dx:number,dy:number,length:number,bend:number){
  const nx=-dy,ny=dx;
  return "M"+fmt(x-dx*length*.45)+" "+fmt(y-dy*length*.45)+
    " Q"+fmt(x+nx*bend)+" "+fmt(y+ny*bend)+
    " "+fmt(x+dx*length*.55+nx*bend*.22)+" "+
      fmt(y+dy*length*.55+ny*bend*.22);
}
