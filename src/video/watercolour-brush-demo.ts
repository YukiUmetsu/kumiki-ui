/** The two independently authored subjects use identical material APIs but unrelated geometry. */
export function paintExampleSpec(aspect: PaintedAspect, subject: PaintedSubject = "wild-iris", seed = 31): PaintSurfaceSpec {
  const portrait = aspect === "portrait";
  const source = subject === "wild-iris" ? IRIS : COAST;
  const convert = (p: Knot): BrushPoint => ({
    x: portrait ? (p[0] - 690) * 1.03 + 270 : p[0],
    y: portrait ? (p[1] - 290) * 1.03 + 620 : p[1],
    pressure: p[2], speed: p[2] < .12 ? .72 : .17,
  });
  const strokes: PaintStroke[] = source.map(([id, color, tone, width, water, load, startFrame, drawFrames, points]) => ({
    id, color, tone, width: portrait ? width * .96 : width, water, load,
    dryBrush: water < .4 ? .72 : water < .65 ? .39 : .10,
    startFrame, drawFrames, spreadFrames: 34, dryFrames: 82,
    points: points.map(convert),
  }));
  return {
    version: 1, medium: "watercolour", width: portrait ? 540 : 960,
    height: portrait ? 960 : 540, seed, paper: { color: "#F7F0E4", tooth: .82 }, strokes,
  };
}
