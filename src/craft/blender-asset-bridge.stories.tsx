/** Real, first-party Blender 4.5.4 export. The .blend and studio QA PNGs are
 * regenerated by the documented kumiki-blender AssetSpec, not shipped to viewers. */
async function createFixture(withPhysics: boolean, withBaked: boolean, withSimulated: boolean, withJoints: boolean): Promise<BlenderRevisionFactory> {
  const model = withJoints ? new URL("./fixtures/blender-mechanical-joints/model.glb", import.meta.url).href
    : withSimulated ? new URL("./fixtures/blender-desk-lamp-physics/model.glb", import.meta.url).href
      : new URL("./fixtures/blender-desk-lamp/model.glb", import.meta.url).href;
  let simulatedActions: BakedPhysicalActionSpec[] | undefined;
  if (withSimulated || withJoints) {
    const url = withJoints ? new URL("./fixtures/blender-mechanical-joints/baked-actions.json", import.meta.url).href
      : new URL("./fixtures/blender-desk-lamp-physics/baked-actions.json", import.meta.url).href;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Cannot fetch Blender simulation sidecar (${response.status}).`);
    simulatedActions = await response.json() as BakedPhysicalActionSpec[];
  }
  return loadBlenderRevision({ manifest: withJoints ? jointsManifest : withSimulated ? simulatedManifest : manifest, model }, { license: "Original first-party Kumiki Blender procedural asset.",
    ...(withPhysics ? { physicalActions: PHYSICAL_ACTIONS } : {}),
    ...(withBaked || withSimulated || withJoints ? { bakedActions: simulatedActions ?? BAKED_ACTIONS } : {}) });
}

function BridgeDemo({ withPhysics = false, withBaked = false, withSimulated = false, withJoints = false }: { withPhysics?: boolean; withBaked?: boolean; withSimulated?: boolean; withJoints?: boolean }) {
  const [factory, setFactory] = useState<BlenderRevisionFactory | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [preset, setPreset] = useState<CameraLightingPreset>(DEFAULT_CAMERA_LIGHTING_PRESET);
  const [role, setRole] = useState(withJoints ? "hinge-arm" : "base-fasteners");
  const [physicalId, setPhysicalId] = useState(withJoints ? "mechanical-joints" : withSimulated ? "fastener-drop" : withBaked ? "fastener-stack" : "arm-sway");
  const activeActions = withJoints ? JOINT_ACTIONS : withSimulated ? SIMULATED_ACTIONS : withBaked ? BAKED_ACTIONS : PHYSICAL_ACTIONS;
  const frameCount = withJoints ? 61 : withSimulated ? 121 : 120;
  const player = useFramePlayer(frameCount, { loop: false });
  useEffect(() => {
    let cancelled = false;
    let owned: BlenderRevisionFactory | null = null;
    void createFixture(withPhysics, withBaked, withSimulated, withJoints).then(result => {
      if (cancelled) result.release();
      else { owned = result; setFactory(result); }
    }).catch(cause => { if (!cancelled) setError(cause instanceof Error ? cause.message : String(cause)); });
    return () => { cancelled = true; owned?.release(); };
  }, [withPhysics, withBaked, withSimulated, withJoints]);
  const createAsset = useCallback(() => {
    if (!factory) throw new Error("Fixture is not loaded yet.");
    return factory();
  }, [factory]);
  const details = useMemo(() => {
    if (!factory) return null;
    const hero = factory();
    try {
      const count = hero.semanticParts.get(role)?.length ?? 0;
      const inspector = factory.createInspectable(hero);
      const firstId = `kumiki:${role}:1`;
      const bounds = count ? inspector.getBounds(firstId, 0) : null;
      return { count, bounds, total: [...hero.semanticParts.values()].reduce((n, nodes) => n + nodes.length, 0),
        roles: [...hero.semanticParts.keys()] };
    } finally { hero.dispose(); }
  }, [factory, role]);
  const impactAudio = useMemo(() => {
    if (!factory || !withSimulated) return null;
    const sounds = bakedContactsToSoundEvents(factory.bakedContactEvents("fastener-drop"), {
      fps: { num: 30, den: 1 }, durationFrames: 120,
      profiles: { "metal-on-floor": { assetRef: "audio/metal-small-impact.wav", gainDb: -12 } },
    });
    const mix = createAudioMixManifest({ id: "fastener-impact-audio", fps: { num: 30, den: 1 },
      durationFrames: 120, lanes: [{ id: "sfx", kind: "sfx", startFrame: 0 }], sounds });
    return { sounds, mix };
  }, [factory, withSimulated]);

  return <main style={{ minHeight: "100vh", background: "#09151a", color: "#eaf2ef", fontFamily: "Inter, system-ui, sans-serif", padding: "clamp(16px, 3vw, 38px)", boxSizing: "border-box" }}>
    <div style={{ maxWidth: 1460, margin: "0 auto" }}>
      <p style={{ color: "#80dbc1", textTransform: "uppercase", letterSpacing: ".15em", fontSize: 11, margin: "0 0 8px" }}>3D asset toolkit / revision handoff</p>
      <h1 style={{ fontSize: "clamp(23px, 3vw, 36px)", fontWeight: 540, margin: "0 0 9px" }}>Blender parts. Kumiki controls.</h1>
      <p style={{ maxWidth: 830, fontSize: 14, lineHeight: 1.6, color: "#b0c5c5", margin: "0 0 21px" }}>
        An actual Blender-exported GLB and audited manifest become a reusable hero asset, separately inspectable parts, and the same camera/lighting editor used across Kumiki scenes. {withJoints ? "Blender 4.5.15 simulates an actual hinge swing, limited linear slider and welded joint. Joint helpers stay in the Blender source and do not become GLB objects; the fixture uses simple QA geometry." : withSimulated ? "Blender 4.5.15 simulated 12 falling metal fasteners, baked their actual rigid-body transforms at 30 fps, and exported the original modeled lamp materials. The collision-only ground stays out of the GLB." : withBaked ? "Baked collision tracks play at arbitrary frames, independent of a physics solver. This demonstration uses authored keyframes, not Blender-simulated data." : withPhysics ? "PM1 adds frame-exact gravity, restitution and damped hinge motion without changing the Blender hierarchy." : "This is a procedural interchange fixture, not a cinematic-quality claim."}
      </p>
      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(min(100%, 365px), 1fr))", gap: 22, alignItems: "start" }}>
        <div style={{ minWidth: 0 }}>
          <div data-km-video-capture="" style={{ width: "100%", border: "1px solid #345057", borderRadius: 14, background: "#111d22", overflow: "hidden", minHeight: 250 }}>
            {factory ? <HeroAssetViewer createAsset={createAsset} cameraLightingPreset={preset} width={960} height={600}
              action={withPhysics || withBaked || withSimulated || withJoints ? physicalId : null} actionFrame={withPhysics || withBaked || withSimulated || withJoints ? player.frame : 0} />
              : <div role="status" style={{ padding: 30 }}>{error ? `Unable to load fixture: ${error}` : "Preparing the local GLB fixture…"}</div>}
          </div>
          {(withPhysics || withBaked || withSimulated || withJoints) && factory && <section style={{ border: "1px solid #304a4b", borderRadius: 12, padding: 16, marginTop: 15, background: "#11252a", display: "grid", gap: 12 }}>
            <h2 style={{ fontSize: 15, fontWeight: 550, margin: 0 }}>{withBaked || withSimulated || withJoints ? "Offline physics bake · 30 fps" : "Physically grounded actions · 30 fps"}</h2>
            <label style={{ display: "grid", gap: 6, fontSize: 12, color: "#b9d4d2" }}>Action
              <select aria-label="Physical action" value={physicalId} onChange={e => { setPhysicalId(e.target.value); player.seek(0); }}
                style={{ borderRadius: 8, padding: "8px 10px", background: "#17333a", color: "#eaf6f2", border: "1px solid #466469" }}>
                {activeActions.map(action => <option key={action.id} value={action.id}>{action.label}</option>)}
              </select>
            </label>
            <div style={{ display: "flex", gap: 9, alignItems: "center" }}>
              <button type="button" onClick={() => player.playing ? player.pause() : player.resume()}
                style={{ background: "#2e8d7a", color: "#fff", border: 0, borderRadius: 8, padding: "9px 13px", cursor: "pointer", fontWeight: 700 }}>
                {player.playing ? "Pause" : "Play"}
              </button>
              <input aria-label="Physical animation frame" type="range" min={0} max={frameCount - 1} value={player.frame}
                onChange={e => player.seek(Number(e.target.value))} style={{ flex: 1, accentColor: "#80dbc1" }} />
              <output aria-label="Physical animation position" style={{ fontVariantNumeric: "tabular-nums", fontSize: 12, minWidth: 72 }}>{player.frame} / {frameCount - 1}</output>
            </div>
            <p style={{ color: "#9bb8b5", fontSize: 12, lineHeight: 1.5, margin: 0 }}>
              {withJoints ? "Three physically constrained bodies: the hinge falls, the slider stops after 0.4 m, and the welded part remains fixed. Scrub to compare their actual Bullet trajectories." : withSimulated ? `All 12 fastener trajectories come from actual Blender Bullet simulation and have ${factory.bakedContactEvents("fastener-drop").length} grounded impact cue candidates for SFX. Contact velocity/time is estimated from simulated floor proximity, not Bullet impulse data.` : withBaked ? `Two fasteners use independent local TRS tracks and ${factory.bakedContactEvents("fastener-stack").length} fractional-frame metal contact cues for sound design. Scrub backward and forward to verify exact playback.` : physicalId === "arm-sway" ? "Upper arm and shade rotate together around the original joint-cover center; mass/gravity length sets swing frequency, damping settles it." :
                `One fastener falls 0.45 m and rebounds. First impact at ${factory.physicalEvents("fastener-drop")[0].timeSeconds.toFixed(3)} s, ${factory.physicalEvents("fastener-drop")[0].speedMps.toFixed(2)} m/s; timestamps can drive SFX.`}
            </p>
          </section>}
          {impactAudio && <section aria-label="Blender impact audio cue QA" style={{ border: "1px solid #304a4b", borderRadius: 12, padding: 16, marginTop: 15, background: "#11252a" }}>
            <h2 style={{ fontSize: 15, fontWeight: 550, margin: "0 0 8px" }}>Impact → sound mix · {impactAudio.sounds.length} cues</h2>
            <p style={{ color: "#9bb8b5", fontSize: 12, lineHeight: 1.5, margin: "0 0 12px" }}>Actual Blender-sampled contact candidates are mapped by material to one sample path, with impact-speed volume and sub-frame timing. Audio path is a placeholder, not a bundled recording; the host video pipeline supplies the licensed WAV.</p>
            <div style={{ maxHeight: 168, overflowY: "auto" }}>
              <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 12, fontVariantNumeric: "tabular-nums", textAlign: "left" }}>
                <thead><tr>{["Cue", "Film time", "Gain"].map(label => <th key={label} style={{ padding: "5px 6px", borderBottom: "1px solid #345057" }}>{label}</th>)}</tr></thead>
                <tbody>{impactAudio.sounds.map((sound, index) => <tr key={sound.id} style={{ background: player.frame === sound.frame ? "#164e49" : "transparent" }}>
                  <td style={{ padding: "5px 6px" }}>{sound.id}</td>
                  <td style={{ padding: "5px 6px" }}>{impactAudio.mix.inputs[index]?.startSeconds.toFixed(3)} s</td>
                  <td style={{ padding: "5px 6px" }}>{sound.gainDb} dB</td>
                </tr>)}</tbody>
              </table>
            </div>
          </section>}
          {details && <section style={{ border: "1px solid #304a4b", borderRadius: 12, padding: 16, marginTop: 15, background: "#11252a" }}>
            <h2 style={{ fontSize: 15, fontWeight: 550, margin: "0 0 12px" }}>Semantic inspection · {details.total} separate nodes</h2>
            <label style={{ fontSize: 12, display: "grid", gap: 7, color: "#b9d4d2" }}>Blender part role
              <select value={role} onChange={e => setRole(e.target.value)} style={{ borderRadius: 8, padding: "10px 12px", background: "#17333a", color: "#eaf6f2", border: "1px solid #466469", fontSize: 14 }}>
                {details.roles.map(id => <option key={id} value={id}>{id}</option>)}
              </select>
            </label>
            <p style={{ fontSize: 13, lineHeight: 1.6, color: "#a8c9c4", margin: "12px 0 0" }}>
              {details.count} separately addressable {details.count === 1 ? "instance" : "instances"}. {details.bounds ? `First instance X extent: ${(details.bounds.max[0] - details.bounds.min[0]).toFixed(2)} m.` : ""}
              <br />Inspectable IDs follow <code>kumiki:{role}:1</code>, <code>kumiki:{role}:2</code>, …
            </p>
          </section>}
        </div>
        <CameraLightingInspector value={preset} onChange={setPreset} onReset={() => setPreset(DEFAULT_CAMERA_LIGHTING_PRESET)} capabilities={{ physicalLights: true }} />
      </div>
    </div>
  </main>;
}

