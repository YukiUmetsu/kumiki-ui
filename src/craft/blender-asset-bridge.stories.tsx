import { useCallback, useEffect, useMemo, useState } from "react";
import type { Meta, StoryObj } from "@storybook/react-vite";
import { HeroAssetViewer } from "../../registry/craft/hero-viewer";
import { loadBlenderRevision } from "../../registry/craft/blender-asset-bridge";
import type { BlenderRevisionFactory } from "../../registry/craft/blender-asset-bridge";
import { CameraLightingInspector } from "../../registry/motion/camera-lighting-inspector";
import { DEFAULT_CAMERA_LIGHTING_PRESET } from "../../registry/motion/camera-lighting-preset";
import type { CameraLightingPreset } from "../../registry/motion/camera-lighting-preset";
import manifest from "./fixtures/blender-desk-lamp/manifest.json";

/** Real, first-party Blender 4.5.4 export. The .blend and studio QA PNGs are
 * regenerated by the documented kumiki-blender AssetSpec, not shipped to viewers. */
async function createFixture(): Promise<BlenderRevisionFactory> {
  const model = new URL("./fixtures/blender-desk-lamp/model.glb", import.meta.url).href;
  return loadBlenderRevision({ manifest, model }, { license: "Original first-party Kumiki Blender procedural asset." });
}

function BridgeDemo() {
  const [factory, setFactory] = useState<BlenderRevisionFactory | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [preset, setPreset] = useState<CameraLightingPreset>(DEFAULT_CAMERA_LIGHTING_PRESET);
  const [role, setRole] = useState("base-fasteners");
  useEffect(() => {
    let cancelled = false;
    let owned: BlenderRevisionFactory | null = null;
    void createFixture().then(result => {
      if (cancelled) result.release();
      else { owned = result; setFactory(result); }
    }).catch(cause => { if (!cancelled) setError(cause instanceof Error ? cause.message : String(cause)); });
    return () => { cancelled = true; owned?.release(); };
  }, []);
  const createAsset = useCallback(() => {
    if (!factory) throw new Error("Fixture is not loaded yet.");
    return factory();
  }, [factory]);
  const details = useMemo(() => {
    if (!factory) return null;
    const hero = factory();
    try {
      const count = hero.semanticParts.get(role)?.length ?? 0;
      const inspector = factory.createInspectable(hero);
      const firstId = `kumiki:${role}:1`;
      const bounds = count ? inspector.getBounds(firstId, 0) : null;
      return { count, bounds, total: [...hero.semanticParts.values()].reduce((n, nodes) => n + nodes.length, 0),
        roles: [...hero.semanticParts.keys()] };
    } finally { hero.dispose(); }
  }, [factory, role]);

  return <main style={{ minHeight: "100vh", background: "#09151a", color: "#eaf2ef", fontFamily: "Inter, system-ui, sans-serif", padding: "clamp(16px, 3vw, 38px)", boxSizing: "border-box" }}>
    <div style={{ maxWidth: 1460, margin: "0 auto" }}>
      <p style={{ color: "#80dbc1", textTransform: "uppercase", letterSpacing: ".15em", fontSize: 11, margin: "0 0 8px" }}>3D asset toolkit / revision handoff</p>
      <h1 style={{ fontSize: "clamp(23px, 3vw, 36px)", fontWeight: 540, margin: "0 0 9px" }}>Blender parts. Kumiki controls.</h1>
      <p style={{ maxWidth: 830, fontSize: 14, lineHeight: 1.6, color: "#b0c5c5", margin: "0 0 21px" }}>
        A real Blender 4.5.4-exported desk-lamp GLB and its audited manifest become a reusable hero asset, separately inspectable parts, and the same camera/lighting editor used across Kumiki scenes. This is a procedural interchange fixture, not a cinematic-quality claim.
      </p>
      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(min(100%, 365px), 1fr))", gap: 22, alignItems: "start" }}>
        <div style={{ minWidth: 0 }}>
          <div data-km-video-capture="" style={{ width: "100%", border: "1px solid #345057", borderRadius: 14, background: "#111d22", overflow: "hidden", minHeight: 250 }}>
            {factory ? <HeroAssetViewer createAsset={createAsset} cameraLightingPreset={preset} width={960} height={600} />
              : <div role="status" style={{ padding: 30 }}>{error ? `Unable to load fixture: ${error}` : "Preparing the local GLB fixture…"}</div>}
          </div>
          {details && <section style={{ border: "1px solid #304a4b", borderRadius: 12, padding: 16, marginTop: 15, background: "#11252a" }}>
            <h2 style={{ fontSize: 15, fontWeight: 550, margin: "0 0 12px" }}>Semantic inspection · {details.total} separate nodes</h2>
            <label style={{ fontSize: 12, display: "grid", gap: 7, color: "#b9d4d2" }}>Blender part role
              <select value={role} onChange={e => setRole(e.target.value)} style={{ borderRadius: 8, padding: "10px 12px", background: "#17333a", color: "#eaf6f2", border: "1px solid #466469", fontSize: 14 }}>
                {details.roles.map(id => <option key={id} value={id}>{id}</option>)}
              </select>
            </label>
            <p style={{ fontSize: 13, lineHeight: 1.6, color: "#a8c9c4", margin: "12px 0 0" }}>
              {details.count} separately addressable {details.count === 1 ? "instance" : "instances"}. {details.bounds ? `First instance X extent: ${(details.bounds.max[0] - details.bounds.min[0]).toFixed(2)} m.` : ""}
              <br />Inspectable IDs follow <code>kumiki:{role}:1</code>, <code>kumiki:{role}:2</code>, …
            </p>
          </section>}
        </div>
        <CameraLightingInspector value={preset} onChange={setPreset} onReset={() => setPreset(DEFAULT_CAMERA_LIGHTING_PRESET)} capabilities={{ physicalLights: true }} />
      </div>
    </div>
  </main>;
}

const meta = { title: "3D asset toolkit/Blender Asset Bridge", id: "craft-blender-asset-bridge", component: BridgeDemo,
  parameters: { layout: "fullscreen" } } satisfies Meta<typeof BridgeDemo>;
export default meta;
export const InterchangeFixture: StoryObj<typeof meta> = {};
