import {test,expect} from "@playwright/test";
test("ANAT6 source-led portraits render all characters and FACS transitions",async({page},info)=>{
 await page.goto("/iframe.html?id=video-ink-anat6-source-led-character-portraits--source-led-qing-character-portraits&viewMode=story",{waitUntil:"domcontentloaded"});
 const atelier=page.getByTestId("ink-anat6-source-led-atelier");
 await expect(atelier).toBeVisible();
 const portrait=atelier.getByTestId("ink-anat6-selected-portrait").locator("svg");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-character","scholar");
 await expect(portrait).toHaveAttribute("data-km-anat1-source","468-point-face-mesh");
 await expect(atelier.locator("[data-km-ink-anat6-reference-card]")).toHaveCount(10);
 await expect(atelier.locator("[data-km-ink-anat6-reference-card] img")).toHaveCount(6);
 await expect(atelier.getByTestId("ink-anat6-expression-contact-sheet").locator("svg")).toHaveCount(8);
 await page.screenshot({fullPage:true,animations:"disabled",path:info.outputPath("anat6-scholar-source-led-neutral.png")});
 await atelier.getByRole("combobox",{name:"Source-led character"}).selectOption("shepherd");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-headwear","wrapped-hood");
 await atelier.getByRole("combobox",{name:"Source-led character"}).selectOption("zhong-kui");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-headwear","loose-hair");
 await atelier.getByRole("combobox",{name:"Source-led character"}).selectOption("lady");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-source-object","Met 52.177.5");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-headwear","pinned-hair");
 await expect(portrait).toHaveAttribute("data-km-ink-anat6-beard","none");
 await expect(portrait.locator('[data-km-ink-anat6-flower="peony"]')).toHaveCount(1);
 await expect(portrait.locator("[data-km-ink-anat6-earring]")).toHaveCount(2);
 await expect(portrait.locator('[data-km-ink-anat6-folded-fan="true"]')).toHaveCount(1);
 await atelier.getByRole("combobox",{name:"Source-led transition from"}).selectOption("sad");
 await atelier.getByRole("combobox",{name:"Source-led expression"}).selectOption("smile");
 const transition=atelier.getByRole("slider",{name:"Source-led expression transition frame"});
 await transition.evaluate(el=>{
  const input=el as HTMLInputElement,setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value")?.set;
  if(!setter)throw new Error("Range slider setter unavailable");
  setter.call(input,"6");input.dispatchEvent(new Event("input",{bubbles:true}));input.dispatchEvent(new Event("change",{bubbles:true}));
 });
 await expect(portrait).toHaveAttribute("data-km-expr1-transition-progress","0.5");
 await expect(portrait).toHaveAttribute("data-km-expr1-transition-from","sad");
 await page.screenshot({fullPage:true,animations:"disabled",path:info.outputPath("anat6-lady-sad-to-smile-frame06-1x.png")});
 await transition.focus();await transition.press("End");
 await expect(portrait).toHaveAttribute("data-km-expr1-transition-progress","1");
 await page.screenshot({fullPage:true,animations:"disabled",path:info.outputPath("anat6-lady-smile-frame12-1x.png")});
 await page.setViewportSize({width:1900,height:1400});
 await atelier.getByTestId("ink-anat6-selected-portrait").evaluate(el=>{const n=el as HTMLElement;n.style.width="1410px";n.style.maxWidth="none";});
 await portrait.screenshot({animations:"disabled",path:info.outputPath("anat6-lady-smile-face-3x.png")});
});
